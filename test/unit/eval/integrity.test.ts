test('candidate cannot replace judge and actual requests retain separate usage accounts', async () =>
  withTmpDir(async (d) => {
    await fixture(d, { judge: { rubric: 'The answer must be correct.' } });
    const variant = join(d, 'variant');
    await cp(defaultPromptsDir, variant, { recursive: true });
    await writeFile(join(variant, 'system.md'), 'ACTOR CANDIDATE');
    await writeFile(join(variant, 'judge.md'), 'CANDIDATE JUDGE ALWAYS PASSES');
    const calls: string[] = [],
      completed: string[] = [];
    const [result] = await runEval({
      ...options(d),
      promptsDir: variant,
      onModelCall: (kind) => {
        calls.push(kind);
      },
      onModelResult: (kind) => {
        completed.push(kind);
      },
      providerFactory: () =>
        scripted(
          (req) => {
            assert.match(req.system, /ACTOR CANDIDATE/);
            return { text: 'done', usage: { input: 11, output: 3 } };
          },
          (req) => {
            assert.match(req.system, /You are grading/);
            assert.doesNotMatch(req.system, /CANDIDATE JUDGE/);
            return {
              text: '{"score":0,"pass":false,"reason":"Incorrect"}',
              thinking: 'PRIVATE_JUDGE_THINKING',
              usage: { input: 17, output: 5 },
            };
          },
        ),
    });
    assert.equal(result?.status, 'fail');
    assert.deepEqual(calls, ['actor', 'judge']);
    assert.deepEqual(completed, calls);
    assert.deepEqual(result?.modelCalls, { actor: 1, judge: 1 });
    assert.equal(result?.modelUsage?.actor.input, 11);
    assert.equal(result?.modelUsage?.judge.input, 17);
    assert.equal(result?.usage.input, 28);
    assert.deepEqual(result?.judgeResponse, {
      stopReason: 'end',
      text: '{"score":0,"pass":false,"reason":"Incorrect"}',
    });
    assert.deepEqual(readResults(join(d, 'run'))[0]?.judgeResponse, result?.judgeResponse);
    assert.doesNotMatch(JSON.stringify(result), /PRIVATE_JUDGE_THINKING/);
    const snapshots = (await readFile(result!.requestSnapshotsPath!, 'utf8'))
      .trim()
      .split('\n')
      .map((line) => JSON.parse(line));
    assert.match(snapshots[0].system, /ACTOR CANDIDATE/);
    assert.equal(snapshots[0].tools.length, 4);
    assert.equal(snapshots[1].tools.length, 0);
    assert.match(await readFile(join(d, 'run', 'evaluator', 'judge.md'), 'utf8'), /You are grading/);
  }));

test('invalid judge final text remains available without losing usage accounts', async () =>
  withTmpDir(async (d) => {
    await fixture(d, { judge: { rubric: 'The answer must be correct.' } });
    const finalText = 'The answer requires further assessment; the verdict is incomplete.';
    const [result] = await runEval({
      ...options(d),
      providerFactory: () =>
        scripted(
          { text: 'done', usage: { input: 11, output: 3 } },
          {
            text: finalText,
            thinking: 'PRIVATE_JUDGE_THINKING',
            stopReason: 'maxTokens',
            usage: { input: 17, output: 2048 },
          },
        ),
    });
    assert.equal(result?.status, 'fail');
    assert.ok(result?.judge && 'error' in result.judge);
    assert.deepEqual(result?.judgeResponse, { stopReason: 'maxTokens', text: finalText });
    const persisted = readResults(join(d, 'run'))[0]!;
    assert.deepEqual(persisted.judgeResponse, result.judgeResponse);
    assert.doesNotMatch(JSON.stringify(persisted), /PRIVATE_JUDGE_THINKING/);
    assert.deepEqual(persisted.modelCalls, { actor: 1, judge: 1 });
    assert.equal(persisted.modelUsage?.actor.output, 3);
    assert.equal(persisted.modelUsage?.judge.output, 2048);
    assert.equal(persisted.usage.input, 28);
    assert.equal(persisted.usage.output, 2051);
  }));

test('provider budget callback stops later calls without losing completed usage', async () =>
  withTmpDir(async (d) => {
    await fixture(d);
    let requested = 0;
    const [result] = await runEval({
      ...options(d),
      onModelCall: () => {
        if (++requested > 1) throw new Error('Model budget exhausted');
      },
      providerFactory: () =>
        scripted({ toolCalls: [{ name: 'read', args: { path: 'check.cjs' } }], usage: { input: 19, output: 7 } }),
    });
    assert.equal(result?.status, 'harnessError');
    assert.match(result?.checkOutputTail ?? '', /budget/);
    assert.deepEqual(result?.modelCalls, { actor: 1, judge: 0 });
    assert.equal(result?.usage.input, 19);
  }));

test('provenance redacts credentials while retaining effective model and inference settings', async () =>
  withTmpDir(async (d) => {
    await fixture(d);
    const config = defaultConfig();
    config.models[config.model] = {
      baseUrl: 'https://eval-user:eval-password@example.invalid/v1?api_key=fixture-secret&version=2',
      contextWindow: 65432,
    };
    const [result] = await runEval({ ...options(d), config });
    const serialized = await readFile(join(d, 'run', 'run.json'), 'utf8');
    assert.doesNotMatch(serialized, /eval-password|fixture-secret|eval-user/);
    const provenance = readManifest(join(d, 'run')).provenance!;
    assert.equal(provenance.model.contextWindow, 65432);
    assert.equal(provenance.model.maxOutputTokens, 8192);
    assert.match(String(provenance.model.baseUrl), /version=2/);
    assert.doesNotMatch(
      await readFile(result!.requestSnapshotsPath!, 'utf8'),
      /eval-password|fixture-secret|eval-user/,
    );
  }));

test('comparison allows actor variants but refuses changed fixtures, configuration and judge', async () =>
  withTmpDir(async (d) => {
    const root = await fixture(d);
    await runEval(options(d, 'base'));
    const variant = join(d, 'variant');
    await cp(defaultPromptsDir, variant, { recursive: true });
    await writeFile(join(variant, 'system.md'), 'Different actor prompt');
    await runEval({ ...options(d, 'variant-run'), promptsDir: variant });
    assert.equal(compareRuns(join(d, 'base'), join(d, 'variant-run')).comparable, true);
    await writeFile(join(root, 'files', 'fixture.txt'), 'Changed input');
    await runEval(options(d, 'fixture-run'));
    assert.equal(compareRuns(join(d, 'base'), join(d, 'fixture-run')).comparable, false);
    await rm(join(root, 'files', 'fixture.txt'));
    const config = defaultConfig();
    config.thinking = 'high';
    await runEval({ ...options(d, 'config-run'), config });
    assert.equal(compareRuns(join(d, 'base'), join(d, 'config-run')).comparable, false);
    await writeFile(join(variant, 'judge.md'), 'Changed judge');
    await runEval({ ...options(d, 'judge-run'), evaluatorPromptsDir: variant });
    assert.equal(compareRuns(join(d, 'base'), join(d, 'judge-run')).comparable, false);
  }));

test('comparison rejects missing, duplicated and corrupt attempts while retaining legacy summaries', async () =>
  withTmpDir(async (d) => {
    await fixture(d);
    await runEval(options(d, 'base'));
    await runEval(options(d, 'candidate'));
    const candidate = join(d, 'candidate'),
      path = join(candidate, 'results.jsonl');
    const rows = readResults(candidate),
      line = JSON.stringify(rows[0]) + '\n';
    await appendFile(path, line);
    assert.match(compareRuns(join(d, 'base'), candidate).incompatibilities.join('\n'), /duplicate/);
    await writeFile(path, '');
    assert.match(compareRuns(join(d, 'base'), candidate).incompatibilities.join('\n'), /missing result/);
    await writeFile(path, '{bad json');
    assert.match(compareRuns(join(d, 'base'), candidate).incompatibilities.join('\n'), /cannot read results/);
    await writeFile(path, line);
    const manifest = readManifest(candidate);
    delete manifest.provenance;
    await writeFile(join(candidate, 'run.json'), JSON.stringify(manifest));
    const comparison = compareRuns(join(d, 'base'), candidate);
    assert.equal(comparison.comparable, false);
    assert.equal(comparison.dev.b.passRate, 1);
    assert.match(comparison.incompatibilities.join('\n'), /legacy/);
    await rm(path);
    assert.equal(compareRuns(join(d, 'base'), candidate).comparable, false);
  }));

test('comparison rejects runs with different executable-extension environments', async () =>
  withTmpDir(async (d) => {
    await fixture(d);
    const original = process.env.PATHEXT;
    try {
      process.env.PATHEXT = original ?? '.COM;.EXE;.BAT;.CMD';
      await runEval(options(d, 'baseline'));
      process.env.PATHEXT += ';.MH_ENV_TEST';
      await runEval(options(d, 'candidate'));
      const baseline = readManifest(join(d, 'baseline')).provenance!,
        candidate = readManifest(join(d, 'candidate')).provenance!;
      assert.notEqual(candidate.environmentHash, baseline.environmentHash);
      assert.doesNotMatch(JSON.stringify(candidate), /MH_ENV_TEST/);
      const comparison = compareRuns(join(d, 'baseline'), join(d, 'candidate'));
      assert.equal(comparison.comparable, false);
      assert.match(comparison.incompatibilities.join('\n'), /conditions differ/);
    } finally {
      if (original === undefined) delete process.env.PATHEXT;
      else process.env.PATHEXT = original;
    }
  }));
