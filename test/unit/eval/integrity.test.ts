async function fixture(dir: string, override: Partial<EvalTask> = {}) {
  const root = join(dir, 'tasks', 'a');
  await mkdir(join(root, 'files'), { recursive: true });
  await writeFile(
    join(root, 'task.json'),
    JSON.stringify({
      id: 'a',
      split: 'dev',
      prompt: 'Complete the task.',
      check: { command: 'node check.cjs' },
      protectedFiles: ['check.cjs'],
      ...override,
    }),
  );
  await writeFile(join(root, 'files', 'check.cjs'), 'process.exit(0);\n');
  return root;
}
const options = (dir: string, run = 'run') => ({
  tasksDir: join(dir, 'tasks'),
  runDir: join(dir, run),
  config: defaultConfig(),
  providerFactory: () => scripted({ text: 'done' }),
});

test('protected check tampering is rejected before the altered check executes', async () =>
  withTmpDir(async (d) => {
    await fixture(d);
    const [result] = await runEval({
      ...options(d),
      providerFactory: () =>
        scripted(
          {
            toolCalls: [
              {
                name: 'write',
                args: {
                  path: 'check.cjs',
                  content: "require('node:fs').writeFileSync('was-run', 'yes');process.exit(0);",
                },
              },
            ],
          },
          { text: 'done' },
        ),
    });
    assert.equal(result?.status, 'harnessError');
    assert.match(result?.integrityError ?? '', /check.cjs/);
    assert.equal(existsSync(join(d, 'run', 'workspaces', 'a', '1', 'was-run')), false);
    assert.equal(result?.checkExitCode, undefined);
  }));

